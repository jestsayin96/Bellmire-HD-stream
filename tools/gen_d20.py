#!/usr/bin/env python3
"""
Generate the d20's face geometry: the CSS that places twenty triangles into a
real icosahedron, and the JS matrices that turn any chosen face to the camera.

Run:  python3 web/tools/gen_d20.py
It prints two blocks and writes nothing - paste them into style.css / app.js
between their BEGIN/END markers. Committed so the geometry can be rebuilt and
checked rather than taken on trust; it is a build tool, not page content.

Why a generator: a d20 face sits at an angle no hand-written CSS transform
describes honestly, and a die that lands on a face showing a different number
than the page reports is the one bug a dice toy must not have.
"""
import math

EDGE = 108.0          # px, the length of one triangle edge
PHI = (1 + 5 ** 0.5) / 2

def norm(v):
    m = math.sqrt(sum(c * c for c in v))
    return tuple(c / m for c in v)
def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def add(a, b): return tuple(x + y for x, y in zip(a, b))
def mul(a, s): return tuple(x * s for x in a)
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def dist(a, b): return math.sqrt(sum((x-y)**2 for x, y in zip(a, b)))

# --- the twelve vertices of a regular icosahedron (edge 2 in these coords)
RAW = []
for s1 in (1, -1):
    for s2 in (1, -1):
        RAW += [(0, s1*1, s2*PHI), (s1*1, s2*PHI, 0), (s1*PHI, 0, s2*1)]
RAW = sorted(set(RAW))
assert len(RAW) == 12, len(RAW)

# scale so the edge length is EDGE
SCALE = EDGE / 2.0
V = [mul(v, SCALE) for v in RAW]
E = EDGE

# --- the twenty faces: every triple of vertices that are pairwise one edge apart
faces = []
for i in range(12):
    for j in range(i+1, 12):
        if abs(dist(V[i], V[j]) - E) > 1e-6: continue
        for k in range(j+1, 12):
            if abs(dist(V[i], V[k]) - E) > 1e-6: continue
            if abs(dist(V[j], V[k]) - E) > 1e-6: continue
            faces.append((i, j, k))
assert len(faces) == 20, len(faces)

CIRCUM = math.sqrt(sum(c*c for c in V[0]))
INRADIUS = (E / 12.0) * math.sqrt(3) * (3 + math.sqrt(5))

# --- number the faces so opposite faces sum to 21, as a real d20 does
centres = []
for (i, j, k) in faces:
    c = mul(add(add(V[i], V[j]), V[k]), 1/3.0)
    centres.append(c)

label = [None] * 20
nxt = 1
for a in range(20):
    if label[a] is not None: continue
    # the antipodal face: the one whose centre is furthest away
    b = min(range(20), key=lambda t: dot(norm(centres[t]), norm(centres[a])))
    label[a] = nxt
    label[b] = 21 - nxt
    nxt += 1
assert sorted(label) == list(range(1, 21)), label
for a in range(20):
    b = min(range(20), key=lambda t: dot(norm(centres[t]), norm(centres[a])))
    assert label[a] + label[b] == 21

# --- a frame per face: u,v in the face plane, n its outward normal
TRI_H = E * math.sqrt(3) / 2.0           # height of an equilateral triangle
CENTROID_OFF = TRI_H / 6.0               # element centre -> triangle centroid

def frame(f):
    i, j, k = faces[f]
    c = centres[f]
    n = norm(c)
    # u along one edge, v completing a right-handed set
    u = norm(sub(V[j], V[i]))
    v = cross(n, u)
    return u, v, n, c

def m3d(cols):
    """column-major 4x4 for CSS matrix3d"""
    u, v, n, c = cols
    vals = list(u)+[0]+list(v)+[0]+list(n)+[0]+list(c)+[1]
    return "matrix3d(" + ",".join(("%.5f" % x).rstrip("0").rstrip(".") or "0" for x in vals) + ")"

def transpose_m3d(cols):
    """The cage rotation that brings this face square to the camera (+Z).
    The placement basis is M = [u v n] (columns). We want R with R*n = +Z and
    R*u = +X, R*v = +Y, which is R = M^T. In column-major matrix3d, the columns
    of M^T are the ROWS of M: (u0,v0,n0), (u1,v1,n1), (u2,v2,n2)."""
    u, v, n, _ = cols
    col0 = (u[0], v[0], n[0])
    col1 = (u[1], v[1], n[1])
    col2 = (u[2], v[2], n[2])
    vals = list(col0)+[0]+list(col1)+[0]+list(col2)+[0]+[0,0,0,1]
    return [round(x, 5) for x in vals]

css, js = [], []
for f in range(20):
    cols = frame(f)
    css.append(".d20face.f%d{transform:%s translateY(%.3fpx)}" % (f, m3d(cols), -CENTROID_OFF))
    js.append((label[f], transpose_m3d(cols)))

print("/* ---- BEGIN generated by web/tools/gen_d20.py - do not hand-edit ---- */")
print(".d20cage{width:%.3fpx;height:%.3fpx}" % (E, TRI_H))
print(".d20face{width:%.3fpx;height:%.3fpx;margin-left:%.3fpx;margin-top:%.3fpx}"
      % (E, TRI_H, -E/2.0, -TRI_H/2.0))
print("\n".join(css))
print("/* edge %.1fpx, circumradius %.2fpx, inradius %.2fpx */" % (E, CIRCUM, INRADIUS))
print("/* ---- END generated ---- */")
print()
print("// ---- BEGIN generated by web/tools/gen_d20.py - do not hand-edit ----")
print("// [face value, the die rotation that brings that face to the camera]")
print("const D20_FACES = [")
for lab, m in js:
    print("  [%d, [%s]]," % (lab, ",".join(repr(x) for x in m)))
print("];")
print("// ---- END generated ----")
