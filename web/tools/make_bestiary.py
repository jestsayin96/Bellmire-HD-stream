#!/usr/bin/env python3
"""Derive the Bestiary's chamber-holder thumbnails and GENERATE the BEAST_DEX block in web/app.js (System 41, section 1).

One command:  python3 web/tools/make_bestiary.py
Reads (never writes): scripts/delve.gd (the MB_NAME table: key -> display name)
                      renders/art/minibosses/<key>/front.png (art's portrait)
Writes:               web/icons/beasts/<key>.webp (W x H, one size), web/icons/beasts/_manifest.json
                      the block between the BEAST_DEX markers in web/app.js
Only keys that have BOTH an MB_NAME row and a front.png are listed; the key and the path are page
constants. A snapshot value never builds a path - it can only select which listed key is drawn.
Budget: web/icons/beasts/ under 1 MB; exits non-zero if over.
"""
import json, os, re, sys
from PIL import Image
W, H, QUALITY, BUDGET = 112, 156, 82, 1024 * 1024
BEGIN = "// BEAST_DEX:BEGIN (generated by web/tools/make_bestiary.py - do not edit by hand)"
END = "// BEAST_DEX:END"
here = os.path.dirname(os.path.abspath(__file__)); repo = os.path.abspath(os.path.join(here, "..", ".."))
t = open(os.path.join(repo, "scripts", "delve.gd"), encoding="utf8").read()
i = t.index("const MB_NAME := {"); j = t.index("\n}", i)
pairs, seen = [], set()
for k, n in re.findall(r'"([a-z_]+)":\s*"([^"\n]+)"', t[i:j]):
    if k in seen or not n[:1].isupper(): continue      # first row per key wins; a display name is capitalised (other tables share the block)
    seen.add(k); pairs.append((k, n))
out = os.path.join(repo, "web", "icons", "beasts"); os.makedirs(out, exist_ok=True)
rows, total = [], 0
for k, name in sorted(pairs):
    src = os.path.join(repo, "renders", "art", "minibosses", k, "front.png")
    if not os.path.isfile(src): continue
    im = Image.open(src).convert("RGBA"); bb = im.getbbox()
    if bb: im = im.crop(bb)
    im.thumbnail((W, H), Image.LANCZOS)
    canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    canvas.paste(im, ((W - im.width) // 2, H - im.height), im)
    dst = os.path.join(out, k + ".webp"); canvas.save(dst, "WEBP", quality=QUALITY, method=6)
    total += os.path.getsize(dst); rows.append((k, name))
if total > BUDGET: sys.exit("over budget: %d" % total)
json.dump({"w": W, "h": H, "count": len(rows), "bytes": total, "keys": [r[0] for r in rows]}, open(os.path.join(out, "_manifest.json"), "w"), indent=1)
lines = [BEGIN, "// %d chamber-holders; thumbnails %dx%d webp, %d bytes" % (len(rows), W, H, total), "const BEAST_DEX = ["]
for k, n in rows: lines.append("  [%s, %s]," % (json.dumps(k), json.dumps(n, ensure_ascii=True)))
lines += ["];", END]
ap = os.path.join(repo, "web", "app.js"); s = open(ap, encoding="utf8").read()
if BEGIN in s:
    a = s.index(BEGIN); b = s.index(END) + len(END); s = s[:a] + "\n".join(lines) + s[b:]
    open(ap, "w", encoding="utf8", newline="").write(s)
else:
    open(os.path.join(here, "_beast_dex_block.txt"), "w").write("\n".join(lines)); print("markers absent; block written to tools/_beast_dex_block.txt")
print(len(rows), "beasts,", total, "bytes")
