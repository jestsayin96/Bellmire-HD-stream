#!/usr/bin/env python3
"""Derive the hub's item-icon thumbnails and GENERATE the app.js whitelist (H32 pass 4).

One command:   python3 web/tools/make_item_icons.py [--commit <art-commit-sha>]
Guard only:    python3 web/tools/make_item_icons.py --verify    (no writes; exit 1 on any empty/short/undecodable icon)

Reads (never writes):  assets/icons/items/<slot>/<key>.png   (the ART lane's originals, 256 px)
                       data/items.json                       (key -> display name)
Writes:                web/icons/items/<slot>/<key>.webp      (THUMB x THUMB, one size only)
                       web/icons/items/_manifest.json         (source commit, size, byte total, files, names)
                       the block between the ITEM_ICONS markers in web/app.js

WHY a whitelist keyed by item NAME: a snapshot item name must never become a URL. app.js looks the
(control-stripped, lower-cased) name up in a Map; a hit yields a page-constant "slot/key" path, a miss
falls through to the SVG glyph. The Map is generated here from the manifest data - never hand-typed - so
it cannot drift from the files on disk. Two items sharing a name keep the first key (sorted) and the
clash is recorded under "conflicts" in the manifest.

THUMB = 160: the largest box the grid or the hover preview displays is 80 css px; 2x that, nothing larger.
Budget (supervisor, 2026-11-16 20:05 CT): the whole web/icons/items/ directory under 6 MB. This script
exits non-zero if it is over.
"""
import argparse, json, os, re, shutil, subprocess, sys
from PIL import Image

THUMB = 160
QUALITY = 85
BUDGET = 6 * 1024 * 1024
BEGIN = "// ITEM_ICONS:BEGIN (generated by web/tools/make_item_icons.py - do not edit by hand)"
END = "// ITEM_ICONS:END"

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, "..", ".."))
ap = argparse.ArgumentParser()
ap.add_argument("--commit", default="", help="source commit of assets/icons/items (read from git if omitted)")
ap.add_argument("--verify", action="store_true", help="only check web/icons/items against its manifest; write nothing")
args = ap.parse_args()


def verify_icons(out_root):
    """The zero-byte guard. hat/turbary_hood.webp sat at 0 bytes from 17 Nov while the manifest still said
    2718 and no gate noticed. Every file under out_root must be non-empty, match the byte count the manifest
    recorded, and decode as an image of THUMB x THUMB. Returns a list of problems (empty = clean)."""
    bad = []
    mp = os.path.join(out_root, "_manifest.json")
    try:
        man = json.load(open(mp, encoding="utf-8"))
    except Exception as e:
        return ["manifest unreadable: %s" % e]
    listed = {f["path"]: f["bytes"] for f in man.get("files", [])}
    for dp, _dn, fns in os.walk(out_root):
        for fn in fns:
            if not fn.endswith(".webp"): continue
            full = os.path.join(dp, fn)
            rel = os.path.relpath(full, out_root).replace(os.sep, "/")
            n = os.path.getsize(full)
            if n == 0: bad.append("ZERO BYTES: " + rel); continue
            if rel not in listed: bad.append("not in manifest: " + rel)
            elif listed[rel] != n: bad.append("size %d != manifest %d: %s" % (n, listed[rel], rel))
            try:
                with Image.open(full) as im:
                    im.load()
                    if im.size != (THUMB, THUMB): bad.append("size %s: %s" % (im.size, rel))
            except Exception as e:
                bad.append("undecodable (%s): %s" % (e, rel))
    for rel in listed:
        if not os.path.isfile(os.path.join(out_root, rel)): bad.append("in manifest, missing on disk: " + rel)
    return bad


src_root = os.path.join(repo, "assets", "icons", "items")
out_root = os.path.join(repo, "web", "icons", "items")
if args.verify:
    problems = verify_icons(out_root)
    for pr in problems: print("RED:", pr)
    print("verify: %s (%d problem(s))" % ("RED" if problems else "GREEN", len(problems)))
    sys.exit(1 if problems else 0)
commit = args.commit
if not commit:
    try:
        commit = subprocess.run(["git", "log", "-1", "--format=%H", "--", "assets/icons/items"], cwd=repo,
                                capture_output=True, text=True).stdout.strip()
    except Exception:
        commit = ""
if not commit:
    sys.exit("need --commit (git is not readable from here): the last commit touching assets/icons/items")

# key -> display name (accessories and cosmetics both carry {name, ...})
items = json.load(open(os.path.join(repo, "data", "items.json"), encoding="utf-8"))
names = {}
def walk(o):
    if isinstance(o, dict):
        for k, v in o.items():
            if isinstance(v, dict) and isinstance(v.get("name"), str): names.setdefault(k, v["name"])
            walk(v)
    elif isinstance(o, list):
        for v in o: walk(v)
walk(items)

files, namemap, conflicts, missing_name = [], {}, [], []
if os.path.isdir(out_root): shutil.rmtree(out_root, ignore_errors=True)  # overwrite in place where deletion is not permitted
for slot in sorted(os.listdir(src_root)):
    sd = os.path.join(src_root, slot)
    if not os.path.isdir(sd): continue
    for f in sorted(os.listdir(sd)):
        if not f.endswith(".png"): continue
        key = f[:-4]
        rel = slot + "/" + key
        dst = os.path.join(out_root, slot, key + ".webp")
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        im = Image.open(os.path.join(sd, f)).convert("RGBA").resize((THUMB, THUMB), Image.LANCZOS)
        im.save(dst, "WEBP", quality=QUALITY, method=6)
        files.append({"path": rel + ".webp", "bytes": os.path.getsize(dst)})
        nm = names.get(key)
        if not nm: missing_name.append(rel); continue
        nk = re.sub(r"\s+", " ", nm).strip().lower()
        if nk in namemap: conflicts.append({"name": nm, "kept": namemap[nk], "dropped": rel})
        else: namemap[nk] = rel

total = sum(f["bytes"] for f in files)
manifest = {"source_commit": commit, "source_dir": "assets/icons/items", "thumb_px": THUMB, "format": "webp",
            "quality": QUALITY, "count": len(files), "total_bytes": total, "named": len(namemap),
            "conflicts": conflicts, "no_name_in_items_json": missing_name, "files": files, "names": namemap}
json.dump(manifest, open(os.path.join(out_root, "_manifest.json"), "w", encoding="utf-8"), indent=1, sort_keys=True)

# generate the whitelist block in app.js FROM the manifest data
lines = [BEGIN,
         "// source commit " + commit + "; " + str(len(namemap)) + " names; thumbnails " + str(THUMB) + "px webp, " + str(total) + " bytes",
         "const ITEM_ICONS = new Map(["]
for nk in sorted(namemap): lines.append("  [" + json.dumps(nk) + ", " + json.dumps(namemap[nk]) + "],")
lines += ["]);", END]
block = "\n".join(lines)
p = os.path.join(repo, "web", "app.js")
s = open(p, encoding="utf-8").read()
if BEGIN in s and END in s:
    i = s.index(BEGIN); j = s.index(END) + len(END)
    s = s[:i] + block + s[j:]
    open(p, "w", encoding="utf-8").write(s)
else:
    sys.exit("markers not found in web/app.js")
print("icons:", len(files), "named:", len(namemap), "conflicts:", len(conflicts), "no-name:", len(missing_name),
      "total bytes:", total, "(%.2f MB)" % (total / 1048576))
problems = verify_icons(out_root)
for pr in problems: print("RED:", pr)
if problems: sys.exit("ICON GUARD RED: %d problem(s) above" % len(problems))
if total > BUDGET: sys.exit("OVER BUDGET: %d bytes > %d" % (total, BUDGET))
